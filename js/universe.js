/** One bounded canvas loop. Hidden tabs stop drawing; mobile uses fewer stars. */
export class SpaceRenderer {
  constructor(canvas) {
    this.canvas = canvas;
    this.ctx = canvas.getContext("2d");
    this.motion = matchMedia("(prefers-reduced-motion: reduce)");
    this.pointerMedia = matchMedia("(hover: hover) and (pointer: fine)");
    this.abort = new AbortController();
    this.dust = [];
    this.pointer = { x: 0, y: 0 };
    this.index = 0;
    this.lastDust = 0;
    this.resize();
    const options = { signal: this.abort.signal };
    window.addEventListener("resize", () => this.resize(), options);
    document.addEventListener(
      "visibilitychange",
      () => {
        document.body.classList.toggle("tab-hidden", document.hidden);
        cancelAnimationFrame(this.frame);
        this.dust.length = 0;
        if (!document.hidden) this.draw(performance.now());
      },
      options,
    );
    this.motion.addEventListener(
      "change",
      () => {
        cancelAnimationFrame(this.frame);
        this.dust.length = 0;
        this.draw(performance.now());
      },
      options,
    );
    document.addEventListener(
      "pointermove",
      (event) => {
        if (!this.pointerMedia.matches || this.motion.matches) return;
        this.pointer.x = (event.clientX / innerWidth - 0.5) * 10;
        this.pointer.y = (event.clientY / innerHeight - 0.5) * 10;
        const now = performance.now();
        if (now - this.lastDust > 38 && this.dust.length < 35) {
          this.lastDust = now;
          this.dust.push({
            x: event.clientX,
            y: event.clientY,
            born: now,
            vx: (Math.random() - 0.5) * 0.5,
            vy: Math.random() * 0.7,
            hue: Math.random() > 0.5 ? "238,160,214" : "184,159,245",
          });
        }
      },
      options,
    );
    this.draw(performance.now());
  }

  resize() {
    this.width = innerWidth;
    this.height = innerHeight;
    const dpr = Math.min(devicePixelRatio || 1, 1.7);
    this.canvas.width = Math.round(this.width * dpr);
    this.canvas.height = Math.round(this.height * dpr);
    this.ctx?.setTransform(dpr, 0, 0, dpr, 0, 0);
    this.stars = Array.from({ length: innerWidth < 600 ? 105 : 230 }, () => ({
      x: Math.random() * this.width,
      y: Math.random() * this.height,
      size: Math.random() * 1.15 + 0.2,
      phase: Math.random() * Math.PI * 2,
      speed: Math.random() * 0.3 + 0.1,
    }));
    if (this.motion.matches) this.draw(performance.now());
  }

  setUniverse(index) {
    this.index = index;
    if (this.motion.matches) this.draw(performance.now());
  }

  draw(time) {
    if (!this.ctx || document.hidden) return;
    const ctx = this.ctx;
    const still = this.motion.matches;
    const t = still ? 0 : time / 1000;
    ctx.clearRect(0, 0, this.width, this.height);
    for (const star of this.stars) {
      const x =
        (star.x + t * star.speed * 1.5 + this.pointer.x * star.size) %
        (this.width + 5);
      const y =
        (star.y -
          t * star.speed * 0.5 +
          this.height * 10 +
          this.pointer.y * star.size) %
        this.height;
      const alpha = still
        ? 0.5
        : 0.32 + Math.sin(t * star.speed + star.phase) * 0.22;
      ctx.fillStyle =
        this.index >= 4
          ? `rgba(246,219,193,${alpha})`
          : `rgba(222,207,246,${alpha})`;
      ctx.beginPath();
      ctx.arc(x, y, star.size, 0, Math.PI * 2);
      ctx.fill();
      if (star.size > 1.2) {
        ctx.strokeStyle = `rgba(229,207,245,${alpha * 0.4})`;
        ctx.lineWidth = 0.5;
        ctx.beginPath();
        ctx.moveTo(x - 3, y);
        ctx.lineTo(x + 3, y);
        ctx.moveTo(x, y - 3);
        ctx.lineTo(x, y + 3);
        ctx.stroke();
      }
    }
    if (!still) {
      const cycle = t % 13;
      if (cycle < 1.4) {
        const x = this.width * 0.8 - cycle * 270,
          y = this.height * 0.08 + cycle * 105;
        const streak = ctx.createLinearGradient(x, y, x + 100, y - 39);
        streak.addColorStop(0, "#f5dfff99");
        streak.addColorStop(1, "transparent");
        ctx.strokeStyle = streak;
        ctx.lineWidth = 1;
        ctx.beginPath();
        ctx.moveTo(x, y);
        ctx.lineTo(x + 100, y - 39);
        ctx.stroke();
      }
      this.dust = this.dust.filter((particle) => time - particle.born < 800);
      for (const particle of this.dust) {
        const age = (time - particle.born) / 800;
        ctx.fillStyle = `rgba(${particle.hue},${(1 - age) * 0.7})`;
        ctx.beginPath();
        ctx.arc(
          particle.x + particle.vx * age * 30,
          particle.y + particle.vy * age * 30,
          (1 - age) * 1.7,
          0,
          Math.PI * 2,
        );
        ctx.fill();
      }
      this.frame = requestAnimationFrame((now) => this.draw(now));
    }
  }

  destroy() {
    cancelAnimationFrame(this.frame);
    this.abort.abort();
    this.dust.length = 0;
  }
}
